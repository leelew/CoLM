#include <define.h>

#ifdef DataAssimilation
MODULE MOD_DA_Vars_TimeInVars
!-----------------------------------------------------------------------------
! DESCRIPTION:
!   Defines and manages the time-invariant model variables required by the
!   data assimilation workflow.
!
!   This module stores the DA ensemble copies of time-invariant fields. Soil
!   hydraulic parameters are perturbed once per ensemble member and remain
!   fixed over the whole integration period, so they are kept separately from
!   the time-varying ensemble storage in MOD_DA_Vars_TimeVars.
!
!   Ensemble copies include an unperturbed open-loop copy and a set of
!   perturbed members. The open-loop copy is used for restoration and
!   diagnostics; the perturbed members are used in ensemble propagation.
!
!   The standard normal draws used to perturb the soil parameters are
!   generated by mkinidata and stored in the const file, so that the model
!   integration only reads and applies them.
!
! HISTORY:
!   Zhilong Fan, 11/2026: Initial version
!-----------------------------------------------------------------------------
   USE MOD_Precision
   USE MOD_Namelist
   USE MOD_Vars_Global
   USE MOD_SPMD_Task
   USE MOD_LandPatch, only: numpatch
   USE MOD_NetCDFSerial, only: ncio_define_dimension, &
      ncio_write_serial_real8_2d, ncio_read_bcast_serial_real8_2d
   IMPLICIT NONE
   SAVE

!=============================================================================
! Ensemble soil hydraulic parameters
!=============================================================================
   real(r8), allocatable           :: porsl_ens  (:,:,:)  ! Fraction of soil that is voids                     [-]
   real(r8), allocatable           :: hksati_ens (:,:,:)  ! Saturated hydraulic conductivity                   [mm/s]

!=============================================================================
! Standard normal draws for soil parameter perturbation
!=============================================================================
   real(r8), allocatable           :: z_soil_ptb (:,:)    ! Standard normal draws (nvar_ptb, ens): row 1 porsl, row 2 hksati [-]

!-----------------------------------------------------------------------------

CONTAINS

!-----------------------------------------------------------------------------

   SUBROUTINE allocate_DA_TimeInVars()

!-----------------------------------------------------------------------------
      IF (p_is_worker) THEN
         IF (numpatch > 0) THEN
            IF (.not. allocated(porsl_ens )) allocate(porsl_ens  (nl_soil,0:DEF_DA_ENS_NUM,numpatch))
            IF (.not. allocated(hksati_ens)) allocate(hksati_ens (nl_soil,0:DEF_DA_ENS_NUM,numpatch))
         ENDIF
      ENDIF

   END SUBROUTINE allocate_DA_TimeInVars

!-----------------------------------------------------------------------------

   SUBROUTINE deallocate_DA_TimeInVars()

!-----------------------------------------------------------------------------
      IF (allocated(porsl_ens )) deallocate(porsl_ens )
      IF (allocated(hksati_ens)) deallocate(hksati_ens)
      IF (allocated(z_soil_ptb)) deallocate(z_soil_ptb)

   END SUBROUTINE deallocate_DA_TimeInVars

!-----------------------------------------------------------------------------

   SUBROUTINE init_z_soil_ptb()

!-----------------------------------------------------------------------------
! DESCRIPTION:
!   Generate the standard normal draws used to perturb the soil hydraulic
!   parameters. Each perturbed parameter (row 1: porsl, row 2: hksati) gets
!   one draw per ensemble member; a single draw is shared by all patches and
!   layers, representing a global adjustment of the soil parameter dataset.
!
!   This is called by mkinidata only. The draws are stored in the const file
!   and reused by every model run.
!-----------------------------------------------------------------------------
      INTEGER :: i, k
      real(r8), allocatable :: u1(:), u2(:)

      IF (DEF_DA_ENS_NUM < 2 .or. mod(DEF_DA_ENS_NUM,2) /= 0) THEN
         CALL CoLM_stop ('ERROR: DEF_DA_ENS_NUM must be > 1 and even to generate z_soil_ptb.')
      ENDIF

      IF (allocated(z_soil_ptb)) deallocate(z_soil_ptb)
      allocate (z_soil_ptb(2, DEF_DA_ENS_NUM))
      allocate (u1(DEF_DA_ENS_NUM/2), u2(DEF_DA_ENS_NUM/2))

      CALL random_seed ()
      DO k = 1, 2
         CALL random_number (u1)
         CALL random_number (u2)
         DO i = 1, DEF_DA_ENS_NUM/2
            u1(i) = max(u1(i), 1.0e-10_r8)
            z_soil_ptb(k,2*i-1) = sqrt(-2.0_r8*log(u1(i))) * cos(2.0_r8*pi*u2(i))
            z_soil_ptb(k,2*i)   = sqrt(-2.0_r8*log(u1(i))) * sin(2.0_r8*pi*u2(i))
         ENDDO
      ENDDO

      deallocate (u1, u2)

   END SUBROUTINE init_z_soil_ptb

!-----------------------------------------------------------------------------

   SUBROUTINE WRITE_DA_TimeInVars(file_restart)

!-----------------------------------------------------------------------------
      character(len=*), intent(in) :: file_restart

      IF (.not. (DEF_DA .and. DEF_DA_ENS_SOILPARAM)) RETURN

      CALL init_z_soil_ptb ()
      CALL ncio_define_dimension (file_restart, 'nvar_ptb', 2)
      CALL ncio_define_dimension (file_restart, 'ens', DEF_DA_ENS_NUM)
      CALL ncio_write_serial_real8_2d (file_restart, 'z_soil_ptb', z_soil_ptb, 'nvar_ptb', 'ens')

      deallocate (z_soil_ptb)

   END SUBROUTINE WRITE_DA_TimeInVars

!-----------------------------------------------------------------------------

   SUBROUTINE READ_DA_TimeInVars(file_restart)

!-----------------------------------------------------------------------------
      character(len=*), intent(in) :: file_restart

      IF (.not. (DEF_DA .and. DEF_DA_ENS_SOILPARAM)) RETURN

      CALL ncio_read_bcast_serial_real8_2d (file_restart, 'z_soil_ptb', z_soil_ptb)
      IF (any(shape(z_soil_ptb) /= [2, DEF_DA_ENS_NUM])) &
         CALL CoLM_stop ('ERROR: z_soil_ptb shape mismatch in const; rerun mkinidata.')

   END SUBROUTINE READ_DA_TimeInVars

!-----------------------------------------------------------------------------
END MODULE MOD_DA_Vars_TimeInVars
#endif
